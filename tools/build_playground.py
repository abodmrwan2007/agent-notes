"""Assembles the Swift Playgrounds variant of the app.

Output:  build/playground/AgentNotes.swiftpm      (open on iPad with Swift Playgrounds)
         build/playground/AgentNotes.swiftpm.zip  (the same, for transfer)

The playground is GENERATED from the same sources as the Xcode app; never edit the output.
Differences from the Xcode app, all applied here:

* One module: the core package sources are copied in and `import AgentNotesCore` is removed.
* The library index uses playground/LibraryDatabase.swift (a JSON file) instead of SQLite/GRDB,
  so the iPad does not have to download and compile a third-party package.
* No Info.plist, so the `.agentnote` type cannot be declared. The type is derived from the
  file extension instead; importing native packages may not work in the playground.
* Arabic comes from generated .lproj/.strings files instead of the string catalog.

Run from the repository root:  python tools/build_playground.py
"""
import pathlib
import shutil
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from build_strings import AR  # noqa: E402

OUT_DIR = ROOT / "build" / "playground"
PACKAGE = OUT_DIR / "AgentNotes.swiftpm"

PACKAGE_SWIFT = '''// swift-tools-version: 5.9

// GENERATED by tools/build_playground.py. Do not edit; edit the app sources and regenerate.

import PackageDescription
import AppleProductTypes

let package = Package(
    name: "AgentNotes",
    defaultLocalization: "en",
    platforms: [
        .iOS("17.0")
    ],
    products: [
        .iOSApplication(
            name: "Agent Notes",
            targets: ["AppModule"],
            bundleIdentifier: "com.agentnotes.playground",
            teamIdentifier: "",
            displayVersion: "0.1.0",
            bundleVersion: "1",
            appIcon: .placeholder(icon: .pencil),
            accentColor: .presetColor(.cyan),
            supportedDeviceFamilies: [
                .pad
            ],
            supportedInterfaceOrientations: [
                .portrait,
                .landscapeRight,
                .landscapeLeft,
                .portraitUpsideDown
            ],
            capabilities: [
                .faceID(purposeString: "Face ID unlocks the notebooks you have locked."),
                .microphone(purposeString: "The microphone records lectures while you take notes. Recordings stay inside your notebook.")
            ]
        )
    ],
    targets: [
        .executableTarget(
            name: "AppModule",
            path: ".",
            resources: [
                .process("Resources")
            ]
        )
    ]
)
'''

# (text to find, replacement). Each must match at least once or the build fails loudly.
PATCHES = {
    "Config/AppConfig.swift": [
        (
            'static let agentNote: UTType = UTType(exportedAs: "com.agentnotes.document")',
            'static let agentNote: UTType = UTType(filenameExtension: "agentnote", conformingTo: .package) ?? .package',
        ),
    ],
}


def strings_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_strings(path: pathlib.Path, table: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* GENERATED by tools/build_playground.py */"]
    for key in sorted(table):
        lines.append(f'"{strings_escape(key)}" = "{strings_escape(table[key])}";')
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def copy_swift(source: pathlib.Path, destination: pathlib.Path, relative: str) -> None:
    text = source.read_text(encoding="utf-8")
    text = "\n".join(line for line in text.splitlines() if line.strip() != "import AgentNotesCore") + "\n"
    for old, new in PATCHES.get(relative, []):
        if old not in text:
            sys.exit(f"patch target not found in {relative}: {old}")
        text = text.replace(old, new)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8")


def build() -> int:
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    PACKAGE.mkdir(parents=True)

    count = 0
    app = ROOT / "App"
    for source in sorted(app.rglob("*.swift")):
        relative = source.relative_to(app).as_posix()
        if relative == "Storage/LibraryDatabase.swift":
            continue  # replaced by the JSON store below
        copy_swift(source, PACKAGE / "App" / relative, relative)
        count += 1

    copy_swift(ROOT / "playground" / "LibraryDatabase.swift", PACKAGE / "App" / "Storage" / "LibraryDatabase.swift", "")
    count += 1

    core = ROOT / "Packages" / "AgentNotesCore" / "Sources" / "AgentNotesCore"
    for source in sorted(core.glob("*.swift")):
        copy_swift(source, PACKAGE / "Core" / source.name, "")
        count += 1

    # Vector sticker artwork (Twemoji, CC BY 4.0) as an asset catalog.
    shutil.copytree(ROOT / "App" / "Resources" / "Twemoji.xcassets", PACKAGE / "Resources" / "Twemoji.xcassets")
    # Labelled medical diagrams (original artwork) and their label data.
    shutil.copytree(ROOT / "App" / "Resources" / "Diagrams.xcassets", PACKAGE / "Resources" / "Diagrams.xcassets")
    write_strings(PACKAGE / "Resources" / "ar.lproj" / "Localizable.strings", AR)
    write_strings(PACKAGE / "Resources" / "en.lproj" / "Localizable.strings", {key: key for key in AR})
    (PACKAGE / "Package.swift").write_text(PACKAGE_SWIFT, encoding="utf-8")

    archive = OUT_DIR / "AgentNotes.swiftpm.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
        for path in sorted(PACKAGE.rglob("*")):
            if path.is_file():
                bundle.write(path, path.relative_to(OUT_DIR).as_posix())
    print(f"wrote {count} Swift files to {PACKAGE}")
    print(f"wrote {archive} ({archive.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(build())
